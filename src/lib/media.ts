export type MediaType = 'image' | 'video';

export interface MediaMeta {
  width: number | null;
  height: number | null;
  duration: number | null;
  capturedAt: string | null;
  cameraMake: string | null;
  cameraModel: string | null;
  lens: string | null;
  iso: number | null;
  aperture: string | null;
  shutter: string | null;
  focalLength: string | null;
  lat: number | null;
  lng: number | null;
}

export interface GalleryMedia {
  id: string;
  mediaType: MediaType;
  location: string;
  title: string;
  url: string;
  thumbnail?: string;
  photographer: string;
  category: string;
  tags: string[];
  meta: MediaMeta;
}

function createMeta(overrides: Partial<MediaMeta>): MediaMeta {
  return {
    width: null,
    height: null,
    duration: null,
    capturedAt: null,
    cameraMake: null,
    cameraModel: null,
    lens: null,
    iso: null,
    aperture: null,
    shutter: null,
    focalLength: null,
    lat: null,
    lng: null,
    ...overrides,
  };
}

